const dicts: Record<Lang, Dict> = { en, id };
const STORAGE_KEY = "plgen_lang";

interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number | undefined>) => string;
}

const I18nContext = createContext<I18nValue>({
  lang: "en",
  setLang: () => {},
  t: (key) => key,
});

function interpolate(s: string, vars?: Record<string, string | number | undefined>): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars && vars[k] !== undefined ? String(vars[k]) : ""));
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      return stored === "id" ? "id" : "en";
    } catch {
      return "en";
    }
  });

  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(STORAGE_KEY, l); } catch {}
  };

  const t = (key: string, vars?: Record<string, string | number | undefined>): string => {
    const s = dicts[lang][key] ?? en[key] ?? key;
    return interpolate(s, vars);
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useLanguage(): I18nValue {
  return useContext(I18nContext);
}
